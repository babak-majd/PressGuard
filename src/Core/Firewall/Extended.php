<?php
/**
 * Extended WAF management (auto_prepend_file install + snapshot).
 *
 * @package PressGuard
 */

namespace PressGuard\Core\Firewall;

use PressGuard\Plugin;
use PressGuard\Support\Config;

defined( 'ABSPATH' ) || exit;

/**
 * Installs/removes the pre-WordPress WAF (firewall/prepend.php) via
 * auto_prepend_file, and keeps a lightweight snapshot file the prepend reads
 * without a database. Everything here is defensive: installation never fatals,
 * and a missing snapshot just means the prepend fails open.
 */
final class Extended {

	const MARKER = 'PressGuard WAF';

	/**
	 * Plugin container.
	 *
	 * @var Plugin
	 */
	private $plugin;

	/**
	 * Constructor.
	 *
	 * @param Plugin $plugin Container.
	 */
	public function __construct( Plugin $plugin ) {
		$this->plugin = $plugin;
	}

	/**
	 * Wire hooks: keep the snapshot fresh, react to the enable toggle.
	 */
	public function register() {
		add_action(
			'update_option_' . Config::OPTION,
			array( $this, 'on_settings_change' ),
			10,
			2
		);
	}

	/**
	 * Whether the prepend actually executed for this request.
	 *
	 * @return bool
	 */
	public static function is_active() {
		return defined( 'PRESSGUARD_WAF' );
	}

	/**
	 * Absolute path to the prepend bootstrap.
	 *
	 * @return string
	 */
	private static function prepend_path() {
		return PRESSGUARD_DIR . 'firewall/prepend.php';
	}

	/**
	 * Directory + file for the generated snapshot (under uploads).
	 *
	 * @return array{dir:string,file:string}
	 */
	private static function snapshot_target() {
		$uploads = wp_upload_dir();
		$dir     = trailingslashit( $uploads['basedir'] ) . 'pressguard';
		return array(
			'dir'  => $dir,
			'file' => $dir . '/waf-snapshot.php',
		);
	}

	/**
	 * React to settings changes: regenerate the snapshot and (de)install the
	 * prepend to match the enable toggle.
	 *
	 * @param mixed $old Old option value.
	 * @param mixed $new New option value.
	 */
	public function on_settings_change( $old, $new ) {
		$this->generate_snapshot();

		$was = is_array( $old ) && ! empty( $old['firewall']['extended']['enabled'] );
		$now = is_array( $new ) && ! empty( $new['firewall']['extended']['enabled'] );

		if ( $now && ! $was ) {
			$this->install();
		} elseif ( ! $now && $was ) {
			$this->uninstall();
		}
	}

	/**
	 * Build the snapshot array the prepend consumes, and write it atomically.
	 *
	 * @return bool
	 */
	public function generate_snapshot() {
		$config = $this->plugin->config();

		$snapshot = array(
			'enabled'         => $config->is_enabled( 'firewall' ),
			'mode'            => (string) $config->get( 'firewall.mode', 'learning' ),
			'threshold'       => (int) $config->get( 'firewall.threshold', 5 ),
			'whitelist'       => array_values( (array) $config->get( 'ip.whitelist', array() ) ),
			'blacklist'       => array_values( (array) $config->get( 'ip.blacklist', array() ) ),
			'trusted_proxies' => array_values( (array) $config->get( 'ip.trusted_proxies', array() ) ),
			'ua_blocklist'    => array_values( (array) $config->get( 'firewall.ua.blocklist', array() ) ),
			'ua_block_empty'  => (bool) $config->get( 'firewall.ua.block_empty', false ),
			'max_body'        => (int) $config->get( 'firewall.max_body', 0 ),
			'admin_paths'     => $this->admin_paths(),
			'rules'           => $this->rule_definitions( $config ),
		);

		$php = "<?php\n// Generated by PressGuard. Do not edit.\nreturn " . var_export( $snapshot, true ) . ";\n";

		$target = self::snapshot_target();
		if ( ! wp_mkdir_p( $target['dir'] ) ) {
			return false;
		}

		// Harden the directory against direct access / listing.
		$index = $target['dir'] . '/index.php';
		if ( ! file_exists( $index ) ) {
			@file_put_contents( $index, "<?php\n// Silence is golden.\n" ); // phpcs:ignore
		}

		return false !== @file_put_contents( $target['file'], $php, LOCK_EX ); // phpcs:ignore
	}

	/**
	 * Paths where POST-body rules are skipped (admin/login editing contexts).
	 *
	 * @return string[]
	 */
	private function admin_paths() {
		$paths = array( '/wp-admin/', '/wp-login.php', '/wp-cron.php', '/wp-json/' );

		$slug = (string) $this->plugin->config()->get( 'login.custom_url.slug', '' );
		if ( '' !== $slug ) {
			$paths[] = '/' . trim( $slug, '/' );
		}

		return $paths;
	}

	/**
	 * Flatten the active rules into plain arrays for the snapshot (no objects,
	 * so the prepend can rebuild Rule instances cheaply).
	 *
	 * @param Config $config Config service.
	 * @return array[]
	 */
	private function rule_definitions( Config $config ) {
		$out = array();
		foreach ( RuleSet::load( $config ) as $rule ) {
			if ( ! $rule->enabled ) {
				continue;
			}
			$out[] = array(
				'id'       => $rule->id,
				'category' => $rule->category,
				'pattern'  => $rule->pattern,
				'score'    => $rule->score,
				'targets'  => $rule->targets,
				'enabled'  => true,
			);
		}
		return $out;
	}

	/**
	 * Install the auto_prepend_file directive for the detected SAPI.
	 *
	 * @return bool
	 */
	public function install() {
		$this->generate_snapshot();

		if ( $this->is_mod_php() ) {
			return $this->write_htaccess();
		}
		return $this->write_user_ini();
	}

	/**
	 * Remove the directive from both possible locations.
	 */
	public function uninstall() {
		$this->write_htaccess( true );
		$this->write_user_ini( true );
	}

	/**
	 * Is the web SAPI mod_php (so .htaccess php_value works)?
	 *
	 * @return bool
	 */
	private function is_mod_php() {
		$sapi = php_sapi_name();
		return false !== strpos( $sapi, 'apache' );
	}

	/**
	 * Insert/remove our block in the site root .htaccess.
	 *
	 * @param bool $remove Whether to remove instead of insert.
	 * @return bool
	 */
	private function write_htaccess( $remove = false ) {
		require_once ABSPATH . 'wp-admin/includes/misc.php';

		$file = ABSPATH . '.htaccess';
		if ( ! file_exists( $file ) && ! is_writable( ABSPATH ) ) {
			return false;
		}
		if ( file_exists( $file ) && ! is_writable( $file ) ) {
			return false;
		}

		$lines = array();
		if ( ! $remove ) {
			$path  = self::prepend_path();
			$lines = array(
				'<IfModule mod_php.c>',
				'php_value auto_prepend_file "' . $path . '"',
				'</IfModule>',
				'<IfModule mod_php7.c>',
				'php_value auto_prepend_file "' . $path . '"',
				'</IfModule>',
			);
		}

		return insert_with_markers( $file, self::MARKER, $lines );
	}

	/**
	 * Insert/remove the directive in the site root .user.ini (CGI/FPM).
	 *
	 * @param bool $remove Whether to remove instead of insert.
	 * @return bool
	 */
	private function write_user_ini( $remove = false ) {
		$file   = ABSPATH . '.user.ini';
		$begin  = '; BEGIN ' . self::MARKER;
		$end    = '; END ' . self::MARKER;
		$path   = self::prepend_path();
		$block  = $begin . "\nauto_prepend_file=\"" . $path . "\"\n" . $end . "\n";

		$current = file_exists( $file ) ? (string) @file_get_contents( $file ) : ''; // phpcs:ignore

		// Strip any existing block first.
		$pattern = '/' . preg_quote( $begin, '/' ) . '.*?' . preg_quote( $end, '/' ) . "\n?/s";
		$current = preg_replace( $pattern, '', $current );

		if ( ! $remove ) {
			$current .= $block;
		}

		if ( '' === trim( $current ) && ! file_exists( $file ) ) {
			return true;
		}

		return false !== @file_put_contents( $file, $current, LOCK_EX ); // phpcs:ignore
	}
}
